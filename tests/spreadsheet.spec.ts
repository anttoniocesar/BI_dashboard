import { expect, test } from "./fixtures/demo";

test("edição direta, confirmação e navegação de planilha", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("tab", { name: "Análise", exact: true }).click();
  const cell = (address: string) => page.getByRole("gridcell", { name: address, exact: true });
  await cell("B3").click();
  await page.keyboard.type("Temperatura");
  await page.keyboard.press("Enter");
  await expect(cell("B3")).toHaveText("Temperatura");
  await expect(cell("B4")).toBeFocused();
  await cell("B6").click();
  await page.keyboard.type("950");
  await page.keyboard.press("Tab");
  await expect(cell("B6")).toHaveText("950");
  await expect(cell("C6")).toBeFocused();
  await cell("B6").dblclick();
  await page.keyboard.press("End");
  await page.keyboard.press("Backspace");
  await page.keyboard.type("5");
  await page.keyboard.press("Enter");
  await expect(cell("B6")).toHaveText("955");
  await expect(cell("B7")).toBeFocused();
  await page.keyboard.press("ArrowRight");
  await expect(cell("C7")).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(cell("C8")).toBeFocused();
  await page.keyboard.press("ArrowLeft");
  await expect(cell("B8")).toBeFocused();
  await page.keyboard.press("ArrowUp");
  await expect(cell("B7")).toBeFocused();
  await cell("B6").click();
  await page.keyboard.press("Delete");
  await expect(cell("B6")).toBeEmpty();
  await cell("B3").click();
  await page.keyboard.press("Backspace");
  await expect(cell("B3")).toBeEmpty();
  expect(errors).toEqual([]);
});

test("edição por F2, cancelamento, blur, limites e fórmula", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("tab", { name: "Treinamento", exact: true }).click();
  const cell = (address: string) => page.getByRole("gridcell", { name: address, exact: true });
  await cell("F2").click();
  await expect(page.getByLabel("Célula selecionada")).toHaveText("F2");
  await expect(page.getByLabel("Conteúdo da célula")).toHaveValue("=B2*D2+C2*E2");
  await page.keyboard.press("F2");
  await page.getByRole("textbox", { name: "Editar F2", exact: true }).fill("0.50");
  await expect(page.getByLabel("Conteúdo da célula")).toHaveValue("0.50");
  await page.keyboard.press("Escape");
  await expect(cell("F2")).toHaveText("0.16");
  await expect(cell("F2")).toBeFocused();
  await page.keyboard.type("=1+1");
  // A grid click now inserts a formula reference; blur outside the grid commits.
  await page.getByText("Planilha · Treinamento", { exact: true }).click();
  await cell("A1").click();
  await expect(cell("F2")).toHaveText("2");
  await page.keyboard.press("ArrowUp");
  await page.keyboard.press("ArrowLeft");
  await expect(cell("A1")).toBeFocused();
  await cell("L1").click();
  await page.keyboard.press("Tab");
  await expect(cell("A2")).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(cell("L1")).toBeFocused();
  await page.screenshot({ path: "test-results/etapa-1-desktop.png", fullPage: true });
});
